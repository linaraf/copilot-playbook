// ─── Helpers ──────────────────────────────────────────────────────────────────

export function getMenuItemsByChain(chainSlug: string): SeedMenuItem[] {
  return placeholderMenuItems.filter((item) => item.chainSlug === chainSlug)
}

export function getMenuItem(chainSlug: string, itemSlug: string): SeedMenuItem | undefined {
  return placeholderMenuItems.find(
    (item) => item.chainSlug === chainSlug && item.slug === itemSlug
  )
}

export function computeUsOnlyCount(item: SeedMenuItem): number {
  const ukSet = new Set(item.uk_ingredients.map((i) => i.toLowerCase()))
  return item.us_ingredients.filter((i) => !ukSet.has(i.toLowerCase())).length
}

export function computeUkOnlyCount(item: SeedMenuItem): number {
  const usSet = new Set(item.us_ingredients.map((i) => i.toLowerCase()))
  return item.uk_ingredients.filter((i) => !usSet.has(i.toLowerCase())).length
}

